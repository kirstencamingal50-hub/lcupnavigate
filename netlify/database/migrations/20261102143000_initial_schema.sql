CREATE TABLE admin_users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name VARCHAR(160),
  username VARCHAR(80) NOT NULL UNIQUE,
  email VARCHAR(254) UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  email_verified_at TIMESTAMPTZ,
  google_sub VARCHAR(255) UNIQUE,
  role VARCHAR(16) NOT NULL DEFAULT 'editor' CHECK (role IN ('admin','editor','viewer')),
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE admin_auth_challenges (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  token_hash CHAR(64) NOT NULL UNIQUE,
  purpose VARCHAR(20) NOT NULL CHECK (purpose IN ('signup','password_reset')),
  account_id BIGINT REFERENCES admin_users(id) ON DELETE CASCADE,
  email VARCHAR(254) NOT NULL,
  full_name VARCHAR(160),
  username VARCHAR(80),
  password_hash VARCHAR(255),
  code_hash VARCHAR(255) NOT NULL,
  attempts SMALLINT NOT NULL DEFAULT 0 CHECK (attempts BETWEEN 0 AND 255),
  expires_at TIMESTAMP NOT NULL,
  resend_after TIMESTAMP NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_admin_auth_challenge_email ON admin_auth_challenges(email, purpose);
CREATE INDEX idx_admin_auth_challenge_expiry ON admin_auth_challenges(expires_at);

CREATE TABLE admin_setup_state (
  id SMALLINT PRIMARY KEY CHECK (id = 1),
  completed_at TIMESTAMPTZ
);

CREATE TABLE categories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(80) NOT NULL UNIQUE,
  slug VARCHAR(100) NOT NULL UNIQUE,
  sort_order SMALLINT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE locations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(150) NOT NULL,
  kind VARCHAR(16) NOT NULL DEFAULT 'building' CHECK (kind IN ('building','facility')),
  description TEXT,
  image_path VARCHAR(255),
  building_number VARCHAR(40),
  floor_label VARCHAR(80),
  capacity BIGINT CHECK (capacity IS NULL OR capacity BETWEEN 0 AND 4294967295),
  floor_count INTEGER NOT NULL DEFAULT 1 CHECK (floor_count BETWEEN 1 AND 65535),
  department_name VARCHAR(160),
  contact_email VARCHAR(254),
  contact_phone VARCHAR(40),
  website_url VARCHAR(500),
  service_hours VARCHAR(500),
  access_hours VARCHAR(500),
  days_open VARCHAR(160),
  lunch_break VARCHAR(160),
  services TEXT,
  nearby_landmarks VARCHAR(1000),
  accessibility_status BOOLEAN,
  accessibility_details VARCHAR(1000),
  accessibility_features JSONB,
  category_id BIGINT REFERENCES categories(id) ON DELETE SET NULL,
  parent_building_id BIGINT REFERENCES locations(id) ON DELETE SET NULL,
  verified BOOLEAN NOT NULL DEFAULT FALSE,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_locations_name ON locations(name);
CREATE INDEX idx_locations_kind ON locations(kind);
CREATE INDEX idx_locations_active ON locations(active);

CREATE TABLE rooms (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  building_id BIGINT NOT NULL REFERENCES locations(id) ON DELETE RESTRICT,
  route_node_id BIGINT,
  name VARCHAR(150) NOT NULL,
  room_number VARCHAR(50) NOT NULL,
  floor_number SMALLINT NOT NULL DEFAULT 0,
  floor_label VARCHAR(80),
  capacity BIGINT CHECK (capacity IS NULL OR capacity BETWEEN 0 AND 4294967295),
  description TEXT,
  function_description VARCHAR(1000),
  department_head VARCHAR(120),
  contact_info VARCHAR(180),
  contact_email VARCHAR(254),
  contact_phone VARCHAR(40),
  website_url VARCHAR(500),
  department_name VARCHAR(160),
  service_hours VARCHAR(500),
  days_open VARCHAR(160),
  lunch_break VARCHAR(160),
  services TEXT,
  nearby_landmarks VARCHAR(1000),
  accessibility_status BOOLEAN,
  accessibility_details VARCHAR(1000),
  image_path VARCHAR(255),
  category_id BIGINT REFERENCES categories(id) ON DELETE SET NULL,
  verified BOOLEAN NOT NULL DEFAULT FALSE,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_room_building_number_floor UNIQUE(building_id, room_number, floor_number)
);
CREATE INDEX idx_rooms_name ON rooms(name);

CREATE TABLE facility_photos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  location_id BIGINT REFERENCES locations(id) ON DELETE CASCADE,
  room_id BIGINT REFERENCES rooms(id) ON DELETE CASCADE,
  image_path VARCHAR(255) NOT NULL,
  alt_text VARCHAR(255) NOT NULL,
  caption VARCHAR(255),
  sort_order INTEGER NOT NULL DEFAULT 0 CHECK (sort_order BETWEEN 0 AND 65535),
  is_cover BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT chk_facility_photo_owner CHECK (
    (location_id IS NOT NULL AND room_id IS NULL) OR
    (location_id IS NULL AND room_id IS NOT NULL)
  )
);
CREATE INDEX idx_facility_photos_location ON facility_photos(location_id, sort_order);
CREATE INDEX idx_facility_photos_room ON facility_photos(room_id, sort_order);

CREATE TABLE map_nodes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  node_key VARCHAR(80) NOT NULL UNIQUE,
  x NUMERIC(9,2) NOT NULL,
  y NUMERIC(9,2) NOT NULL,
  floor_number SMALLINT NOT NULL DEFAULT 0,
  verified BOOLEAN NOT NULL DEFAULT FALSE,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
ALTER TABLE rooms ADD CONSTRAINT fk_rooms_route_node FOREIGN KEY (route_node_id) REFERENCES map_nodes(id) ON DELETE SET NULL;

CREATE TABLE map_markers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  location_id BIGINT NOT NULL REFERENCES locations(id) ON DELETE CASCADE,
  route_node_id BIGINT REFERENCES map_nodes(id) ON DELETE SET NULL,
  x NUMERIC(9,2) NOT NULL,
  y NUMERIC(9,2) NOT NULL,
  floor_number SMALLINT NOT NULL DEFAULT 0,
  map_key VARCHAR(40) NOT NULL DEFAULT 'campus',
  verified BOOLEAN NOT NULL DEFAULT FALSE,
  accessibility_status BOOLEAN,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_markers_map ON map_markers(map_key, floor_number);

CREATE TABLE map_connections (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  from_node_id BIGINT NOT NULL REFERENCES map_nodes(id) ON DELETE RESTRICT,
  to_node_id BIGINT NOT NULL REFERENCES map_nodes(id) ON DELETE RESTRICT,
  weight NUMERIC(10,2) NOT NULL CHECK (weight > 0),
  connection_type VARCHAR(16) NOT NULL DEFAULT 'walkway' CHECK (connection_type IN ('walkway','stairs','ramp','elevator')),
  verified BOOLEAN NOT NULL DEFAULT FALSE,
  accessibility_status BOOLEAN,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  CONSTRAINT uq_connection_pair UNIQUE(from_node_id, to_node_id)
);
CREATE INDEX idx_connections_to ON map_connections(to_node_id);

CREATE TABLE campus_routes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  start_marker_id BIGINT NOT NULL REFERENCES map_markers(id) ON DELETE RESTRICT,
  destination_marker_id BIGINT NOT NULL REFERENCES map_markers(id) ON DELETE RESTRICT,
  landmark_marker_id BIGINT UNIQUE REFERENCES map_markers(id) ON DELETE CASCADE,
  status VARCHAR(16) NOT NULL DEFAULT 'incomplete' CHECK (status IN ('draft','incomplete','active','inactive')),
  verified BOOLEAN NOT NULL DEFAULT FALSE,
  accessibility_status BOOLEAN,
  distance_map_units NUMERIC(10,2),
  notes VARCHAR(1000),
  created_by BIGINT REFERENCES admin_users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_campus_routes_status ON campus_routes(status);
CREATE INDEX idx_campus_routes_endpoints ON campus_routes(start_marker_id, destination_marker_id);

CREATE TABLE campus_route_points (
  route_id BIGINT NOT NULL REFERENCES campus_routes(id) ON DELETE CASCADE,
  sequence_no SMALLINT NOT NULL,
  node_id BIGINT NOT NULL REFERENCES map_nodes(id) ON DELETE RESTRICT,
  point_type VARCHAR(16) NOT NULL CHECK (point_type IN ('start','waypoint','destination')),
  notes VARCHAR(255),
  PRIMARY KEY(route_id, sequence_no)
);
CREATE INDEX idx_campus_route_point_node ON campus_route_points(node_id);

CREATE TABLE campus_route_segments (
  route_id BIGINT NOT NULL REFERENCES campus_routes(id) ON DELETE CASCADE,
  sequence_no SMALLINT NOT NULL,
  connection_id BIGINT NOT NULL REFERENCES map_connections(id) ON DELETE RESTRICT,
  PRIMARY KEY(route_id, sequence_no)
);
CREATE INDEX idx_campus_route_segment_connection ON campus_route_segments(connection_id);

CREATE TABLE floor_plans (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  building_id BIGINT NOT NULL REFERENCES locations(id) ON DELETE CASCADE,
  floor_number SMALLINT NOT NULL,
  original_name VARCHAR(255) NOT NULL,
  stored_name VARCHAR(255) NOT NULL UNIQUE,
  mime_type VARCHAR(100) NOT NULL,
  file_size NUMERIC(20,0) NOT NULL CHECK (file_size BETWEEN 0 AND 18446744073709551615),
  verified BOOLEAN NOT NULL DEFAULT FALSE,
  uploaded_by BIGINT REFERENCES admin_users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE login_attempts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ip_hash CHAR(64) NOT NULL,
  attempted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_login_attempts_ip_time ON login_attempts(ip_hash, attempted_at);

CREATE TABLE announcements (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(180) NOT NULL,
  body TEXT NOT NULL,
  status VARCHAR(16) NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','published','unpublished')),
  publish_at TIMESTAMP,
  event_start TIMESTAMP,
  event_end TIMESTAMP,
  location_id BIGINT REFERENCES locations(id) ON DELETE SET NULL,
  image_path VARCHAR(255),
  featured BOOLEAN NOT NULL DEFAULT FALSE,
  created_by BIGINT REFERENCES admin_users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_announcement_public ON announcements(status, publish_at);

CREATE TABLE favorites (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_key CHAR(64) NOT NULL,
  location_id BIGINT NOT NULL REFERENCES locations(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_favorite UNIQUE(account_key, location_id)
);

CREATE TABLE audit_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  admin_id BIGINT REFERENCES admin_users(id) ON DELETE SET NULL,
  action VARCHAR(40) NOT NULL,
  entity_type VARCHAR(50) NOT NULL,
  entity_id BIGINT,
  before_json JSONB,
  after_json JSONB,
  ip_address VARCHAR(45),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_audit_entity ON audit_logs(entity_type, entity_id);
CREATE INDEX idx_audit_date ON audit_logs(created_at);

CREATE TABLE app_sessions (
  token_hash CHAR(64) PRIMARY KEY,
  payload JSONB NOT NULL,
  csrf_hash CHAR(64) NOT NULL,
  expires_at TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_app_sessions_expiry ON app_sessions(expires_at);

CREATE TABLE system_settings (
  setting_key VARCHAR(120) PRIMARY KEY,
  setting_value JSONB NOT NULL,
  updated_by BIGINT REFERENCES admin_users(id) ON DELETE SET NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE FUNCTION set_updated_at() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at = CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$;
CREATE TRIGGER trg_admin_users_updated_at BEFORE UPDATE ON admin_users FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_locations_updated_at BEFORE UPDATE ON locations FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_rooms_updated_at BEFORE UPDATE ON rooms FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_map_markers_updated_at BEFORE UPDATE ON map_markers FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_campus_routes_updated_at BEFORE UPDATE ON campus_routes FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_announcements_updated_at BEFORE UPDATE ON announcements FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_system_settings_updated_at BEFORE UPDATE ON system_settings FOR EACH ROW EXECUTE FUNCTION set_updated_at();
