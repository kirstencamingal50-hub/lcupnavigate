create or replace function public.current_admin_role()
returns text
language sql
stable
security definer
set search_path = ''
as $$
  select p.role
  from public.admin_profiles as p
  where p.id = (select auth.uid())
    and p.active
  limit 1
$$;

create or replace function public.has_admin_role(minimum_role text default 'viewer')
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select
    case public.current_admin_role()
      when 'admin' then 3
      when 'editor' then 2
      when 'viewer' then 1
      else 0
    end >= case minimum_role
      when 'admin' then 3
      when 'editor' then 2
      when 'viewer' then 1
      else 4
    end
$$;

create or replace function public.bootstrap_first_admin(p_user_id uuid)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  updated_count integer;
begin
  perform pg_advisory_xact_lock(2026111323);
  if exists (
    select 1 from public.admin_setup_state where id and completed_at is not null
  ) or exists (
    select 1 from public.admin_profiles where role = 'admin' and active
  ) then
    return false;
  end if;

  update public.admin_profiles
  set role = 'admin', active = true
  where id = p_user_id and email_verified_at is not null;
  get diagnostics updated_count = row_count;
  if updated_count <> 1 then
    raise exception 'Verified first-administrator profile was not found';
  end if;

  update public.admin_setup_state set completed_at = now() where id;
  return true;
end;
$$;

