-- NaviGATE department directory: departments may occupy multiple buildings and rooms.
-- Additive migration. Existing locations, rooms, routes and announcements are preserved.
begin;

create table if not exists public.departments (
  id bigint generated by default as identity primary key,
  name varchar(180) not null unique,
  description text,
  office_hours varchar(500),
  contact_email varchar(254),
  contact_phone varchar(40),
  image_path varchar(255),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.department_locations (
  id bigint generated by default as identity primary key,
  department_id bigint not null references public.departments(id) on delete cascade,
  building_id bigint not null references public.locations(id) on delete restrict,
  room_id bigint references public.rooms(id) on delete set null,
  floor_number smallint,
  room_number varchar(50),
  created_at timestamptz not null default now()
);

create index if not exists idx_department_locations_department on public.department_locations(department_id);
create index if not exists idx_department_locations_building on public.department_locations(building_id);
create index if not exists idx_department_locations_room on public.department_locations(room_id);

alter table public.departments enable row level security;
alter table public.department_locations enable row level security;

drop trigger if exists departments_touch_updated_at on public.departments;
create trigger departments_touch_updated_at before update on public.departments
for each row execute function public.touch_updated_at();

commit;
