create or replace function public.bootstrap_first_admin(p_user_id uuid)
returns boolean language plpgsql security definer set search_path=''
as $fn$
declare updated_count integer;
begin
  perform pg_advisory_xact_lock(2026111323);
  if exists(select 1 from public.admin_setup_state where id=1 and completed_at is not null)
     or exists(select 1 from public.admin_users where role='admin' and active) then
    return false;
  end if;
  update public.admin_users set role='admin',active=true,updated_at=now()
   where auth_user_id=p_user_id and email_verified_at is not null;
  get diagnostics updated_count=row_count;
  if updated_count<>1 then raise exception 'Verified first-administrator account was not found'; end if;
  update public.admin_setup_state set completed_at=now() where id=1 and completed_at is null;
  if not found then raise exception 'First-administrator setup state is already complete'; end if;
  return true;
end;
$fn$;

