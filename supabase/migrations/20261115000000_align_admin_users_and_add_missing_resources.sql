-- Supabase Auth owns passwords. This marker is deliberately not a PHP password hash.
create or replace function public.handle_new_auth_user()
returns trigger language plpgsql security definer set search_path=''
as $fn$
declare candidate_username text;
begin
  candidate_username:=coalesce(
    nullif(left(btrim(coalesce(new.raw_user_meta_data->>'username','')),80),''),
    'user_'||left(replace(new.id::text,'-',''),12)
  );
  insert into public.admin_users(auth_user_id,full_name,username,email,password_hash,email_verified_at,role,active)
  values(new.id,
    nullif(left(btrim(coalesce(new.raw_user_meta_data->>'full_name','')),160),''),
    candidate_username,new.email,'SUPABASE_AUTH:'||new.id::text,
    new.email_confirmed_at,'editor',false)
  on conflict(auth_user_id) do update set
    email=excluded.email,email_verified_at=excluded.email_verified_at,updated_at=now();
  return new;
end;
$fn$;

