do $do$
declare identity_mode text; id_default text;
begin
  select is_identity,column_default into identity_mode,id_default
  from information_schema.columns
  where table_schema='public' and table_name='admin_users' and column_name='id';
  if identity_mode='NO' and id_default is null and to_regclass('public.admin_users_id_seq') is not null then
    alter table public.admin_users alter column id set default nextval('public.admin_users_id_seq'::regclass);
  end if;
  if not exists(select 1 from pg_constraint where conrelid='public.admin_users'::regclass and conname='fk_admin_users_auth_user') then
    alter table public.admin_users add constraint fk_admin_users_auth_user
      foreign key(auth_user_id) references auth.users(id) on delete cascade;
  end if;
end;
$do$;

