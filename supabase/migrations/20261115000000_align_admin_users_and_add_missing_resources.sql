create or replace function public.current_admin_role()
returns text language sql stable security definer set search_path=''
as $fn$
  select u.role from public.admin_users u
  where u.auth_user_id=(select auth.uid()) and u.active limit 1
$fn$;

create or replace function public.has_admin_role(minimum_role text default 'viewer')
returns boolean language sql stable security definer set search_path=''
as $fn$
  select case public.current_admin_role()
    when 'admin' then 3 when 'editor' then 2 when 'viewer' then 1 else 0 end
    >= case minimum_role when 'admin' then 3 when 'editor' then 2 when 'viewer' then 1 else 4 end
$fn$;

